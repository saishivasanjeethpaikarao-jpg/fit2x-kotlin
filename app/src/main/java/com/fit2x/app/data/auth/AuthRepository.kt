package com.fit2x.app.data.auth

import android.app.Activity
import android.content.Context
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.play.services.auth.GetGoogleIdOption
import androidx.credentials.play.services.auth.GoogleIdTokenCredential
import androidx.credentials.play.services.auth.GoogleIdTokenParsingException
import com.fit2x.app.data.local.UserProfileDao
import com.google.firebase.FirebaseNetworkException
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseAuthException
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.firestore.FieldValue
import com.google.firebase.firestore.FirebaseFirestore
import com.google.firebase.firestore.SetOptions
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.channels.awaitClose
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.callbackFlow
import kotlinx.coroutines.flow.firstOrNull
import kotlinx.coroutines.flow.flow
import kotlinx.coroutines.flow.flowOn
import kotlinx.coroutines.tasks.await

/**
 * Signed-in (or offline) user identity used across the app.
 */
data class Fit2xUser(
    val uid: String,
    val name: String,
    val email: String,
    val photoUrl: String?
)

/** Result of one Google sign-in attempt. */
sealed interface AuthResult {
    data class Success(val user: Fit2xUser) : AuthResult
    data class Error(val message: String) : AuthResult
    data object Cancelled : AuthResult
}

/**
 * Native Google Sign-In via Credential Manager (NOT the deprecated
 * GoogleSignInClient, NOT a web popup). Links the Google ID token to
 * Firebase Auth, then persists the user to Firestore
 * (`users/{uid}/fit2x/state`) and the local Room [UserProfile].
 *
 * Everything remote is best-effort: sign-in succeeds as long as Firebase
 * Auth succeeds. Firestore/Room writes never fail the sign-in.
 */
class AuthRepository(
    private val appContext: Context,
    private val auth: FirebaseAuth,
    private val firestore: FirebaseFirestore,
    private val profileDao: UserProfileDao
) {
    private val prefs by lazy {
        appContext.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
    }

    /** Firebase auth-state as a cold flow of [Fit2xUser]. */
    fun observeAuthState(): Flow<Fit2xUser?> = callbackFlow {
        val listener = FirebaseAuth.AuthStateListener { firebaseAuth ->
            val fbUser = firebaseAuth.currentUser
            trySend(
                fbUser?.let {
                    Fit2xUser(
                        uid = it.uid,
                        name = it.displayName.orEmpty(),
                        email = it.email.orEmpty(),
                        photoUrl = it.photoUrl?.toString()
                    )
                }
            )
        }
        auth.addAuthStateListener(listener)
        awaitClose { auth.removeAuthStateListener(listener) }
    }

    /**
     * Starts native Google Sign-In. Emits exactly one terminal [AuthResult].
     * Must be called with a foreground [Activity] (Credential Manager needs
     * it to show the account picker UI).
     */
    fun signInWithGoogle(activity: Activity): Flow<AuthResult> = flow {
        // default_web_client_id is generated by the google-services plugin from
        // google-services.json. We look it up at runtime (not via R.string.*)
        // so the app still compiles when the file is missing (e.g. CI).
        val serverClientId = runCatching {
            val resId = appContext.resources.getIdentifier(
                "default_web_client_id", "string", appContext.packageName
            )
            if (resId != 0) appContext.getString(resId) else null
        }.getOrNull()
        if (serverClientId.isNullOrBlank()) {
            emit(AuthResult.Error("Google sign-in isn't configured yet (google-services.json is missing)."))
            return@flow
        }

        val credentialManager = CredentialManager.create(appContext)
        val googleIdOption = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(false)
            .setServerClientId(serverClientId)
            .setAutoSelectEnabled(true)
            .build()
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(googleIdOption)
            .build()

        val response = try {
            credentialManager.getCredential(request = request, activity = activity)
        } catch (e: GetCredentialCancellationException) {
            emit(AuthResult.Cancelled)
            return@flow
        } catch (e: GetCredentialException) {
            emit(AuthResult.Error(mapCredentialError(e)))
            return@flow
        } catch (e: Exception) {
            emit(AuthResult.Error("Couldn't reach Google sign-in: ${e.message ?: "unknown error"}"))
            return@flow
        }

        val googleIdTokenCredential = try {
            GoogleIdTokenCredential.createFrom(response.credential.data)
        } catch (e: GoogleIdTokenParsingException) {
            emit(AuthResult.Error("Couldn't read the Google sign-in response. Please try again."))
            return@flow
        }

        val firebaseCredential =
            GoogleAuthProvider.getCredential(googleIdTokenCredential.idToken, null)
        val authResult = try {
            auth.signInWithCredential(firebaseCredential).await()
        } catch (e: FirebaseNetworkException) {
            emit(AuthResult.Error("No internet connection. Check your network and try again."))
            return@flow
        } catch (e: FirebaseAuthException) {
            emit(AuthResult.Error("Sign-in failed: ${e.message ?: "unknown error"}"))
            return@flow
        } catch (e: Exception) {
            emit(AuthResult.Error("Sign-in failed: ${e.message ?: "unknown error"}"))
            return@flow
        }

        val fbUser = authResult.user
        if (fbUser == null) {
            emit(AuthResult.Error("Sign-in didn't return a user. Please try again."))
            return@flow
        }

        val user = Fit2xUser(
            uid = fbUser.uid,
            name = fbUser.displayName.orEmpty(),
            email = fbUser.email.orEmpty(),
            photoUrl = fbUser.photoUrl?.toString()
        )
        persistUser(user)
        setOfflineMode(false)
        emit(AuthResult.Success(user))
    }.flowOn(Dispatchers.IO)

    /** Full sign-out: Firebase, Credential Manager state, offline flag, local identity. */
    suspend fun signOut() {
        auth.signOut()
        try {
            CredentialManager.create(appContext)
                .clearCredentialState(ClearCredentialStateRequest())
        } catch (_: Exception) {
            // Best-effort: not being able to clear saved credential state
            // must never block sign-out.
        }
        setOfflineMode(false)
        val current = profileDao.observeProfile().firstOrNull()
        if (current != null) {
            profileDao.upsert(current.copy(name = "", email = "", photoUrl = null))
        }
    }

    fun isOfflineMode(): Boolean = prefs.getBoolean(KEY_OFFLINE_MODE, false)

    fun setOfflineMode(offline: Boolean) {
        prefs.edit().putBoolean(KEY_OFFLINE_MODE, offline).apply()
    }

    private fun mapCredentialError(e: GetCredentialException): String = when (e.type) {
        GetCredentialException.TYPE_NO_CREDENTIAL ->
            "No Google accounts on this phone. Add one in Settings > Passwords & accounts, then try again."
        GetCredentialException.TYPE_INTERRUPTED ->
            "Sign-in was interrupted. Please try again."
        else ->
            "Google sign-in failed: ${e.message ?: "unknown error"}"
    }

    /**
     * Best-effort persistence. Firestore write merges into
     * `users/{uid}/fit2x/state` (same path the web app uses); the Room
     * write preserves the user's existing local prefs (theme, goals).
     * Failures are swallowed — the user is already signed in.
     */
    private suspend fun persistUser(user: Fit2xUser) {
        try {
            firestore.collection("users")
                .document(user.uid)
                .collection("fit2x")
                .document("state")
                .set(
                    mapOf(
                        "name" to user.name,
                        "email" to user.email,
                        "photoUrl" to user.photoUrl,
                        "lastLoginAt" to FieldValue.serverTimestamp()
                    ),
                    SetOptions.merge()
                )
                .await()
        } catch (_: Exception) {
            // Offline-first: a failed Firestore write must not fail sign-in.
        }
        try {
            val existing = profileDao.observeProfile().firstOrNull()
            if (existing != null) {
                profileDao.upsert(
                    existing.copy(name = user.name, email = user.email, photoUrl = user.photoUrl)
                )
            } else {
                profileDao.upsert(
                    com.fit2x.app.data.local.UserProfile(
                        name = user.name,
                        email = user.email,
                        photoUrl = user.photoUrl
                    )
                )
            }
        } catch (_: Exception) {
            // Same: local write failure must not fail sign-in.
        }
    }

    private companion object {
        const val PREFS_NAME = "fit2x_auth"
        const val KEY_OFFLINE_MODE = "offline_mode"
    }
}
